const { chromium } = require('/opt/node22/lib/node_modules/playwright');
const fs = require('fs');
const D = '/tmp/claude-0/-home-user-aban-news-landing/4b3d580f-be07-56cf-9e7e-eb1e2c56b229/scratchpad';
const URL_ = fs.readFileSync(D + '/canary_preview_url.txt', 'utf8').trim();
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, userAgent: UA, locale: 'de-CH' });
  const p = await ctx.newPage();
  const errs = [], cartReq = [], log = [];
  p.on('pageerror', (e) => errs.push('PAGEERROR ' + String(e).slice(0, 240)));
  p.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource|Framing|Refused to execute/.test(m.text())) errs.push('console: ' + m.text().slice(0, 200)); });
  await p.route('**/cart/add**', async (route) => { cartReq.push({ methode: route.request().method(), ct: route.request().headers()['content-type'], body: decodeURIComponent((route.request().postData() || '').replace(/\+/g, ' ')).slice(0, 2500) }); await route.abort(); });
  await p.goto(URL_, { waitUntil: 'domcontentloaded', timeout: 60000 });
  await p.waitForTimeout(8000);
  await p.evaluate(() => { const bt = [...document.querySelectorAll('button')].find((x) => /nur notwendige|ablehnen|reject/i.test(x.textContent)); if (bt) bt.click(); });
  const d = p.locator('.lspod-designer-v6'); await d.scrollIntoViewIfNeeded();
  const waehle = async (wert) => { await p.evaluate((w) => document.querySelector(`input[type=radio][value="${w}"]`).click(), wert); await p.waitForTimeout(2500); };
  const zustand = async (l) => log.push({ l, sel: await p.evaluate(() => [...document.querySelectorAll('input[type=radio]:checked')].map((i) => i.value).join('/')), variantId: await p.evaluate(() => (document.querySelector('form[action*="/cart/add"] [name=id]') || {}).value), preis: await p.evaluate(() => (document.querySelector('.price, [class*=price]') || {}).textContent?.replace(/\s+/g, ' ').trim().slice(0, 30)), pod: await p.evaluate(() => { const i = document.querySelector('[name="properties[_pod_karte]"]'); return i ? i.value.slice(0, 160) : null; }), hinweis: await p.evaluate(() => [...document.querySelectorAll('.lspod-designer-v6 [class*=warn],.lspod-designer-v6 [class*=sperre],.lspod-designer-v6 [role=alert]')].map((e) => e.textContent.replace(/\s+/g, ' ').trim().slice(0, 100)).filter(Boolean)) });
  await d.getByRole('button', { name: '➕ Text' }).click();
  await d.locator('textarea, input[type=text]').first().fill('Test Entwurf');
  await p.waitForTimeout(800);
  await zustand('schwarz-325+text');
  await waehle('Rot'); await zustand('rot-325');
  await waehle('444 ml'); await zustand('rot-444');
  await waehle('Blau'); await zustand('blau-444');
  await d.getByRole('button', { name: /Mit meinem Design/ }).click().catch((e) => log.push('Kaufknopf: ' + String(e).slice(0, 100)));
  await p.waitForTimeout(8000);
  await zustand('nach-kauf');
  await p.screenshot({ path: D + '/canary_editor4.png' });
  await b.close();
  fs.writeFileSync(D + '/canary_editor2_ergebnis.json', JSON.stringify({ log, cartReq, errs }, null, 1));
  console.log('fertig');
})().catch((e) => { console.error('FEHLER', e); process.exit(1); });
